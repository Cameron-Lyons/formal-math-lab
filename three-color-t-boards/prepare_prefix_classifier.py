"""Generate the finite prefix classifier for the combined row-five certificates."""

import json
from collections import defaultdict
from itertools import permutations
from pathlib import Path

from prepare_splice import split_rows

ROOT = Path(__file__).resolve().parent
LAYERS = [
    ("SpliceData", "splice_witnesses.json"),
    ("SpliceExtensionData", "splice_extension.json"),
    ("SpliceFurtherData", "splice_further.json"),
    ("SpliceTransferData", "splice_transfer.json"),
]


def prefix_labels(layers):
    labels = {}
    actions = [
        (str.maketrans("012", "".join(p)), reflected)
        for p in permutations("012")
        for reflected in (False, True)
    ]
    for _, data in layers:
        for group in data["groups"]:
            for cap in group["caps"]:
                rows = [*split_rows(cap, 0, data["cut"]), group["pivot"]]
                for action, (palette, reflected) in enumerate(actions):
                    image = [
                        (r[::-1] if reflected else r).translate(palette) for r in rows
                    ]
                    key = int("".join(image), 3)
                    if labels.setdefault(key, action) != action:
                        raise ValueError(
                            f"two actions agree on the full prefix for {rows}"
                        )
    return sorted(labels.items())


def generate_classifier(layers, directory, module_name="SplicePrefixData"):
    """Each layer is the Lean data-module name paired with its parsed witness data."""
    labels = prefix_labels(layers)
    body = []

    def tree(entries):
        if all(v == entries[0][1] for _, v in entries):
            return f"(.label {entries[0][1]})"
        half = len(entries) // 2
        left, right = tree(entries[:half]), tree(entries[half:])
        expression = f"(.branch {entries[half - 1][0]} {left} {right})"
        if len(entries) < 12:
            return expression
        name = f"tree{len(body)}"
        body.append(f"private def {name} : PrefixClassifier := {expression}")
        return name

    cut = layers[0][1]["cut"]
    apex_place = 3 ** ((cut + 1) ** 2 - 1)
    pivot_mod = 3 ** (2 * cut + 1)
    tags = defaultdict(set)

    def short_key(key):
        return (key // apex_place) * pivot_mod + key % pivot_mod

    for key, action in labels:
        tags[short_key(key)].add(action)
    # Use the full six-row key wherever the apex and pivot leave multiple actions possible.
    short = sorted(
        (key, next(iter(values)) if len(values) == 1 else 12)
        for key, values in tags.items()
    )
    ambiguous = [
        (key, action) for key, action in labels if len(tags[short_key(key)]) > 1
    ]
    short_root = tree(short)
    short_action = f"PrefixClassifier.lookup {short_root} ((key / {apex_place}) * {pivot_mod} + key % {pivot_mod})"
    if ambiguous:
        full_root = tree(ambiguous)
        body += [
            "",
            "def classify (key : Nat) : Nat :=",
            f"  let action := {short_action}",
            f"  if action < 12 then action else PrefixClassifier.lookup {full_root} key",
            "",
        ]
    else:
        body += ["", f"def classify (key : Nat) : Nat := {short_action}", ""]
    names = []
    for module, data in layers:
        name = f"classified{module}"
        names.append(name)
        group_proofs = []
        for i in range(len(data["groups"])):
            check = f"{name}_{i}"
            body += [
                f"private theorem {check} : PrefixClassified classify {module}.group{i} := by",
                "  decide +kernel",
            ]
            group_proofs.append(check)
        checks = ", ".join(group_proofs)
        if len(group_proofs) > 1:
            checks = f"⟨{checks}⟩"
        body += [
            "",
            f"theorem {name} : ∀ g ∈ {module}.groups, PrefixClassified classify g := by",
            f"  simp only [{module}.groups, List.forall_mem_cons, List.not_mem_nil,",
            "    false_implies, implies_true, and_true]",
            "  exact " + checks,
            "",
        ]
    groups = layers[0][0] + ".groups"
    proof = names[0]
    for name, (module, _) in zip(names[1:], layers[1:], strict=False):
        groups = f"({groups} ++ {module}.groups)"
        proof = f"List.forall_mem_append.mpr ⟨{proof}, {name}⟩"
    body += [
        f"theorem classified : ∀ g ∈ {groups}, PrefixClassified classify g :=",
        f"  {proof}",
        "",
        f"end TBoards.{module_name}",
    ]
    lines = [
        "import SplicePrefixSymmetry",
        *("import " + mod for mod, _ in layers),
        "",
        "-- Generated by prepare_prefix_classifier.py.",
        "set_option Elab.async false",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "",
        f"namespace TBoards.{module_name}",
        "open Splice",
        "",
        *body,
    ]
    path = directory / (module_name + ".lean")
    source = "\n".join(lines) + "\n"
    if not path.exists() or path.read_text() != source:
        path.write_text(source)


if __name__ == "__main__":
    layers = [
        (module, json.loads((ROOT / witness).read_text())) for module, witness in LAYERS
    ]
    generate_classifier(layers, ROOT)
