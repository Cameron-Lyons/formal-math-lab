"""Rebuild the packed Lean sorting schedules from the extracted computation archive."""

from __future__ import annotations

import argparse
import gzip
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable


def packed(digits: Iterable[int], base: int) -> int:
    """Store the first digit at the least significant position."""
    total = 0
    place = 1
    for digit in digits:
        if not 0 <= digit < base:
            raise ValueError(f"Invalid base-{base} digit {digit}")
        total += digit * place
        place *= base
    return total


def moves_code(word: str, length: int) -> int:
    if len(word) != length:
        raise ValueError(f"Expected {length} moves, found {len(word)}")
    return packed((int(move) - 1 for move in word), 4)


def table(name: str, pairs: Iterable[tuple[int, int]]) -> str:
    lines = [f"  ({a}, {b})" for a, b in pairs]
    return f"def {name} : List (Nat × Nat) := [\n" + ",\n".join(lines) + "]\n"


def rebuild(evidence: Path) -> str:
    rows: dict[tuple[int, ...], int] = {}
    closures = evidence / "coverage/results/n19-ordered/closures"
    for path in sorted(closures.glob("*/words.txt.gz")):
        with gzip.open(path, "rt") as stream:
            for line in stream:
                *cards, word = line.split()
                deck = tuple(map(int, cards))
                if deck in rows or sorted(deck) != list(range(1, 20)):
                    raise ValueError(f"Invalid or repeated deck in {path}")
                rows[deck] = moves_code(word, 76)
    if len(rows) != 384:
        raise ValueError(f"Expected 384 distinct residual decks, found {len(rows)}")

    deletions: list[tuple[int, int]] = []
    path = evidence / "verify/published/deletions.txt"
    records = path.read_text().splitlines()
    if records[:1] != ["UNSORTABLE"]:
        raise ValueError(f"Unexpected header in {path}")
    for record in records[1:]:
        label, word = record.removeprefix("delete ").split(": ")
        deletions.append((int(label), moves_code(word, 80)))
    if sorted(label for label, _ in deletions) != list(range(1, 22)):
        raise ValueError("Expected one sorting word for each of 21 deletions")

    return (
        "-- Generated by build_witnesses.py from the archived physical schedules.\n"
        "namespace ThreeStacks\n\n"
        + table(
            "residualCodes", ((packed(deck, 32), rows[deck]) for deck in sorted(rows))
        )
        + "\n"
        + table("deletionCodes", deletions)
        + "\nend ThreeStacks\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--evidence-root",
        required=True,
        type=Path,
        help="extracted three-stack-bound directory",
    )
    parser.add_argument("output", type=Path, help="destination Witnesses.lean file")
    args = parser.parse_args()
    args.output.write_text(rebuild(args.evidence_root))
