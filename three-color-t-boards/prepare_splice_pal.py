"""Generate the palindromic upper-prefix supplement to the six-layer splice certificate."""

import argparse
import json
import subprocess
from pathlib import Path

from prepare_splice import split_rows
from prepare_splice_extension import generate_packed_data
from prepare_splice_next import generate_next

ROOT = Path(__file__).resolve().parent
WITNESS = "splice_pal.json"
MODULE = "SplicePalData"


def validate_pal(data):
    for i, group in enumerate(data["groups"]):
        if group.get("palindromic_upper") is not True:
            raise ValueError(f"group {i} is missing the palindromic prefix declaration")
        for cap in group["caps"]:
            rows = split_rows(cap + group["pivot"], 0, 6)
            if any(row != row[::-1] for row in rows):
                raise ValueError(f"group {i} contains an asymmetric cap or pivot")
            if list(dict.fromkeys(cap + group["pivot"])) != list("012"):
                raise ValueError(
                    f"group {i} does not use the canonical order of first appearances"
                )
        tails = set(group["tails"])
        for tail in tails:
            reflected = "".join(row[::-1] for row in split_rows(tail, 6, 10))
            if reflected == tail or reflected not in tails:
                raise ValueError(
                    f"group {i} has no distinct reflected partner for tail {tail}"
                )


def generate_pal(directory):
    data = json.loads((directory / WITNESS).read_text())
    validate_pal(data)
    generate_packed_data(
        data, data, directory, further=True, namespace=MODULE, witness=WITNESS
    )
    labeled = generate_next(directory, sixth=True)
    labeled += sum(6 * len(g["caps"]) * len(g["tails"]) for g in data["groups"])
    proof = f"""import SplicePal
import SplicePalData
import SpliceSixthCertificates

-- Generated by prepare_splice_pal.py from splice_pal.json and the six ordinary layers.
set_option Elab.async false
set_option maxRecDepth 100000
set_option maxHeartbeats 0

namespace TBoards
open Splice

/-- Count the six palette images of the palindromic-prefix products alongside the six earlier layers. -/
theorem at_least_{labeled} :
    ∃ f : Fin {labeled} → Board, (∀ i, Valid (f i)) ∧
      (∀ i j, f i = f j → i = j) := by
  apply pal_supplement_lower_bound 5 sixthGroups SplicePalData.groups SpliceSixthPrefixData.classify {labeled}
    sixthChecked sixthCut sixthDistinct SpliceSixthPrefixData.classified SplicePalData.checked
  · decide +kernel
  · decide +kernel
  · decide +kernel
  · rw [sixthSize, SplicePalData.size_sum]
    decide

end TBoards

#print axioms TBoards.at_least_{labeled}
"""
    path = directory / "SplicePalCertificates.lean"
    if not path.exists() or path.read_text() != proof:
        path.write_text(proof)
    return labeled


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--build", action="store_true", help="build the combined Lean theorem"
    )
    args = parser.parse_args()
    count = generate_pal(ROOT)
    print(
        f"Generated the combined Lean certificate for {count:,} labeled boards.",
        flush=True,
    )
    if args.build:
        subprocess.run(["lake", "build", "SplicePalCertificates"], cwd=ROOT, check=True)
